
function [xi, wgp] = getPoints2DTriangle(ngp)

    switch ngp 

        case 1 
            xi = [1/3, 1/3];
           wgp = 1/2; 
        % ................ 
        case 3
            xi = [1/6, 1/6,...
                  2/3, 1/6,...
                  1/6, 2/3];

           wgp = [1/3, 1/3, 1/3];
        % ................ 
        case 6
            xi =  [ 0.816847572980459, 0.091576213509771,...
                    0.091576213509771, 0.816847572980459,...
                    0.091576213509771, 0.091576213509771,...
                    0.108103018168070, 0.445948490915965,...
                    0.445948490915965, 0.108103018168070,...
                    0.445948490915965, 0.445948490915965];

            wgp = [ 0.109951743655322,...
                    0.109951743655322,...
                    0.109951743655322,...
                    0.223381589678011,...
                    0.223381589678011,...
                    0.223381589678011];
             
        % ................   
        otherwise

            error("GaussQuadrature::getPoints2DTriangle: invalid ngp!")
    end

end